def _has(low: str, words) -> bool:
    return any(w.lower() in low for w in words)


def is_failure_notice(text: str) -> bool:
    """テキストがシステム障害・メンテナンス系の告知かを判定。"""
    if not text:
        return False
    t = text.strip()
    low = t.lower()

    if _has(low, DISABILITY):
        return False
    if _has(low, STRONG):
        return True
    if _has(low, CONTEXTUAL) and _has(low, SYSTEM_CONTEXT):
        return True
    return False
